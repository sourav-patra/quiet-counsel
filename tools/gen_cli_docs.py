"""Write docs/cli.md from the argument parser itself, so the reference cannot drift from the
command. Case D-02 regenerates it and fails if the committed copy differs.

It walks the parser rather than printing argparse's own help, because that formatting changes
between Python versions and a docs check that fails on 3.13 but not 3.11 is noise.
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from quiet_counsel import cli  # noqa: E402


def rows(parser):
    out = []
    for act in parser._actions:
        if isinstance(act, (argparse._HelpAction, argparse._SubParsersAction)):
            continue
        name = ", ".join(act.option_strings) if act.option_strings else act.dest
        if act.nargs in ("+", "*"):
            name += " …"
        out.append(f"| `{name}` | {act.help or ''} |")
    return out


def render():
    ap = cli.build_parser()
    subs = next(a for a in ap._actions if isinstance(a, argparse._SubParsersAction))
    helps = {c.dest: c.help for c in subs._choices_actions}
    parts = ["# Command reference", "",
             "Generated by `tools/gen_cli_docs.py` from the parser. Edit the parser, not this file.",
             "", f"`{ap.prog}` {ap.description}", "",
             "| argument | meaning |", "|---|---|", *rows(ap), ""]
    for name, sp in subs.choices.items():
        parts += [f"## {ap.prog} {name}", "", helps.get(name, "").capitalize() + ".", "",
                  "| argument | meaning |", "|---|---|", *rows(sp), ""]
    return "\n".join(parts)


if __name__ == "__main__":
    path = os.path.join(os.path.dirname(__file__), "..", "docs", "cli.md")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render())
    print("wrote docs/cli.md")
